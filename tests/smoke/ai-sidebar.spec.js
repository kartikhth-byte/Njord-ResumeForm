/* global process */
import { test, expect } from '@playwright/test'
import { createFleetFixture, fleetSession } from '../helpers/fleetFixture'

// Browser-only shell fixture: no engine, model, database or production calls.
async function fixture(page, { collapsed = '0', role = 'Recruiter', operator = false } = {}) {
  const state = createFleetFixture({ role, operator })
  await page.addInitScript(({ session, collapsed }) => {
    localStorage.setItem('njord-auth-token', JSON.stringify(session))
    localStorage.setItem('holmes.sidebar.collapsed', collapsed)
  }, { session: fleetSession(), collapsed })
  await page.route('**/*', async route => {
    const req = route.request(), url = new URL(req.url())
    const reply = body => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
    if (url.hostname === 'supabase.invalid') {
      if (url.pathname.endsWith('/needle-token')) return reply({ token: 'synthetic' })
      const result = state.respond(url, req.method(), req.postData() ? req.postDataJSON() : null)
      return route.fulfill({ status: result.status, contentType: 'application/json', body: JSON.stringify(result.body) })
    }
    if (!['localhost', '127.0.0.1'].includes(url.hostname)) return route.abort()
    if (url.pathname === '/ai/auth/holmes') return reply({ ok: true })
    if (url.pathname === '/ai/auth/me') return reply({ authenticated: true })
    if (url.pathname === '/ai/') return route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><body style="background:#191817;color:white;font-family:system-ui"><h1>AI Search fixture</h1><input aria-label="Search resumes" placeholder="Describe who you need"><button>Search</button></body></html>' })
    return route.continue()
  })
}
const sidebar = page => page.locator('#holmes-navigation')
const launcher = page => page.getByRole('button', { name: 'Open Holmes menu', exact: true })
async function ready(page) {
  await page.goto('/recruiter/ai/search')
  await expect(page.frameLocator('iframe').getByRole('heading', { name: 'AI Search fixture' })).toBeVisible()
}

test.describe('AI Search auto-hiding Holmes sidebar', () => {
  test.skip(!process.env.HOLMES_FLEET_SYNTHETIC_SMOKE, 'Requires synthetic Vite server with AI Search on')
  test.use({ storageState: { cookies: [], origins: [] } })
  for (const role of ['Master Recruiter', 'Recruiter']) test(`${role} opens AI Search from navigation and after reload`, async ({ page }) => {
    await fixture(page, { role })
    await page.goto('/recruiter/companies')
    const account = page.getByRole('button', { name: 'Account', exact: true })
    await expect(account.getByText(role, { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Operator', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'AI search', exact: true }).click()
    await expect(page.frameLocator('iframe').getByRole('heading', { name: 'AI Search fixture' })).toBeVisible()
    await page.reload()
    await expect(page.frameLocator('iframe').getByRole('heading', { name: 'AI Search fixture' })).toBeVisible()
  })
  test('Operator identity is prominent while the separate organization role stays visible in the account menu', async ({ page }) => {
    await fixture(page, { operator: true })
    await ready(page)
    await launcher(page).click()
    const account = page.getByRole('button', { name: 'Account', exact: true })
    await expect(account.getByText('Operator', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Operator', exact: true })).toBeVisible()
    await account.click()
    await expect(page.getByRole('menu').getByText('Operator', { exact: true })).toBeVisible()
    await expect(page.getByRole('menu').getByText('Organization role: Recruiter', { exact: true })).toBeVisible()
    await page.screenshot({ path: 'test-results/operator-account-label.png', animations: 'disabled' })
  })
  test('edge opens without resizing or remounting search; leave closes and quick pass stays closed', async ({ page }) => {
    await fixture(page); await ready(page)
    await expect(sidebar(page)).toBeHidden()
    await expect(sidebar(page)).toHaveAttribute('inert', '')
    const frame = page.locator('iframe'), before = await frame.boundingBox()
    expect(before).toMatchObject({ x: 0, y: 0, width: 1280, height: 720 })
    await page.frameLocator('iframe').getByLabel('Search resumes').fill('keep my search')
    await page.mouse.move(2, 250)
    await page.mouse.move(400, 250)
    await page.waitForTimeout(450)
    await expect(sidebar(page)).toBeHidden()
    await page.mouse.move(2, 250)
    await expect(sidebar(page)).toBeVisible()
    await page.mouse.move(120, 250)
    await expect(page.getByRole('button', { name: 'Applications', exact: true })).toBeVisible()
    expect(await frame.boundingBox()).toEqual(before)
    await page.screenshot({ path: 'test-results/ai-sidebar-open.png', animations: 'disabled' })
    await page.mouse.move(600, 250)
    await expect(sidebar(page)).toBeHidden()
    await expect(page.frameLocator('iframe').getByLabel('Search resumes')).toHaveValue('keep my search')
    await page.screenshot({ path: 'test-results/ai-sidebar-closed.png', animations: 'disabled' })
  })
  test('keyboard access, Escape and hidden focus safety', async ({ page }) => {
    await fixture(page); await ready(page)
    await page.mouse.move(2, 250)
    await expect(sidebar(page)).toBeVisible()
    await launcher(page).focus(); await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Holmes home' })).toBeFocused()
    await page.mouse.move(600, 250)
    await page.waitForTimeout(350)
    await expect(sidebar(page)).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(sidebar(page)).toBeHidden()
    await expect(launcher(page)).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Holmes home' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(sidebar(page)).toBeHidden()
    await page.keyboard.press('Tab')
    expect(await sidebar(page).evaluate(el => el.contains(document.activeElement))).toBe(false)
  })
  test('account interaction stays open; clicking inside the iframe dismisses it', async ({ page }) => {
    await fixture(page); await ready(page)
    await launcher(page).click()
    await page.getByRole('button', { name: 'Account', exact: true }).click()
    await page.mouse.move(600, 250)
    await page.waitForTimeout(350)
    await expect(page.getByRole('menuitem', { name: 'Sign out' })).toBeVisible()
    await page.mouse.click(600, 250)
    await expect(sidebar(page)).toBeHidden()
    await expect(page.getByRole('menuitem', { name: 'Sign out' })).toBeHidden()
  })
  for (const collapsed of ['0', '1']) test(`ordinary pages restore sidebar preference ${collapsed}`, async ({ page }) => {
    await fixture(page, { collapsed }); await ready(page)
    await launcher(page).click()
    await page.getByRole('button', { name: 'Companies & ships', exact: true }).click()
    await expect(page).toHaveURL(/\/recruiter\/companies$/)
    await expect(page.locator('html')).toHaveAttribute('data-rail', collapsed === '1' ? 'collapsed' : 'expanded')
    await expect(sidebar(page)).toBeVisible()
    await expect(launcher(page)).toHaveCount(0)
    expect(await page.evaluate(() => localStorage.getItem('holmes.sidebar.collapsed'))).toBe(collapsed)
    await page.getByRole('button', { name: 'AI search', exact: true }).click()
    await expect(sidebar(page)).toBeHidden()
  })
  test('touch-sized search has full viewport, accessible menu and close button', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await fixture(page); await ready(page)
    expect(await page.locator('iframe').boundingBox()).toMatchObject({ x: 0, y: 0, width: 390, height: 844 })
    await launcher(page).click()
    await expect(page.getByRole('button', { name: 'Applications', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Close Holmes menu', exact: true }).click()
    await expect(sidebar(page)).toBeHidden()
    await expect(launcher(page)).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  })
  test('Coordinator access remains denied', async ({ page }) => {
    await fixture(page, { role: 'Coordinator' }); await page.goto('/recruiter/companies')
    await expect(page.getByRole('button', { name: 'Account', exact: true }).getByText('Coordinator', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'AI search', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Operator', exact: true })).toHaveCount(0)
    await page.goto('/recruiter/ai/search')
    await expect(page).toHaveURL(/\/unauthorized$/)
    await expect(page.locator('iframe')).toHaveCount(0)
  })
})
