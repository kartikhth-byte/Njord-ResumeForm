import { createFleetFixture, fleetSession } from '../helpers/fleetFixture'

async function fixture(page, options) {
  const state=createFleetFixture(options)
  await page.addInitScript(session => localStorage.setItem('njord-auth-token',JSON.stringify(session)), fleetSession())
  await page.route('**/*', async route => {
    const req=route.request(), url=new URL(req.url())
    if(['127.0.0.1','localhost'].includes(url.hostname)) return route.continue()
    if(url.hostname!=='supabase.invalid') return route.abort()
    const result=state.respond(url,req.method(),req.postData()?req.postDataJSON():null)
    await route.fulfill({status:result.status,contentType:'application/json',body:JSON.stringify(result.body)})
  })
  return state
}
async function noOverflow(page) {
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  if (page.viewportSize().width >= 768) await expect.poll(() => page.evaluate(() => document.querySelector('main').getBoundingClientRect().left >= document.querySelector('.recruiter-sidebar').getBoundingClientRect().right - 1)).toBe(true)
}

