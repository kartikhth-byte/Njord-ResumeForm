export const createEmptySection14Course = () => ({
  courseName: '',
  imoModelCourse: '',
  referenceRegulation: '',
  certificateNumber: '',
  dateOfIssue: '',
  dateOfExpiry: '',
})

export function getSection14CourseMetadata(courseName) {
  return SECTION14_COURSE_METADATA[courseName] || {
    imoModelCourse: '',
    referenceRegulation: '',
  }
}

export function normalizeSection14Course(course = {}) {
  const courseName = course.courseName || ''
  const metadata = getSection14CourseMetadata(courseName)

  return {
    courseName,
    imoModelCourse: metadata.imoModelCourse,
    referenceRegulation: metadata.referenceRegulation,
    certificateNumber: course.certificateNumber || '',
    dateOfIssue: course.dateOfIssue || '',
    dateOfExpiry: course.dateOfExpiry || '',
  }
}

export function normalizeSection14Courses(courses) {
  if (!Array.isArray(courses)) return []
  return courses.map((course) => normalizeSection14Course(course))
}
